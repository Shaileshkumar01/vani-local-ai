from __future__ import annotations

from typing import Annotated, Any, Literal, TypedDict

# --- LangChain / LangGraph Imports (with local fallback runner if not installed) ---
try:
    from langchain_core.messages import AIMessage, BaseMessage, HumanMessage, SystemMessage
    from langchain_core.tools import tool
    from langchain_ollama import ChatOllama
    from langgraph.checkpoint.memory import MemorySaver
    from langgraph.graph import END, START, StateGraph
    from langgraph.graph.message import add_messages
    from langgraph.prebuilt import ToolNode

    LANGGRAPH_AVAILABLE = True
except ImportError:
    LANGGRAPH_AVAILABLE = False

    def tool(fn):  # type: ignore
        return fn


# 1. Define Shared Graph State Schema
class AgentState(TypedDict):
    task: str
    plan: list[str]
    current_step: int
    tool_outputs: list[str]
    final_answer: str


# 2. Define Domain Tools for Research Summarization
@tool
def search_domain_knowledge(query: str) -> str:
    """Search domain knowledge base and documentation for research summarization."""
    return f"[KnowledgeRetrieved] Verified best practices and data for: {query}"


@tool
def execute_automation_action(action_name: str, payload: str) -> str:
    """Execute an automated workflow step for research summarization."""
    return f"[ActionExecuted] Completed '{action_name}' with payload: {payload}"


@tool
def generate_report_artifact(summary: str) -> str:
    """Save the final structured automation output report."""
    return f"[ReportSaved] Research Summarization report finalized: {summary}"


TOOLS = [search_domain_knowledge, execute_automation_action, generate_report_artifact]


# 3. Define LangGraph Nodes
def planner_node(state: AgentState) -> dict[str, Any]:
    """Break the user's research summarization goal into structured execution steps."""
    goal = state["task"]
    plan = [
        f"Step 1: Analyze requirements and context for '{goal}'",
        f"Step 2: Execute automated research summarization tool actions",
        f"Step 3: Verify outputs and compile final summary",
    ]
    print(f"[PlannerNode] Created {len(plan)}-step plan for: {goal}")
    return {"plan": plan, "current_step": 0, "tool_outputs": []}


def agent_executor_node(state: AgentState) -> dict[str, Any]:
    """Execute the current step in the plan using bound LangChain tools."""
    idx = state["current_step"]
    step_desc = state["plan"][idx]
    print(f"[AgentNode] Executing -> {step_desc}")

    if idx == 0:
        out = search_domain_knowledge(state["task"])
    elif idx == 1:
        out = execute_automation_action("research_summarization_workflow", state["task"])
    else:
        out = generate_report_artifact(f"Successfully automated {state['task']}")

    updated_outputs = list(state.get("tool_outputs", [])) + [str(out)]
    return {"current_step": idx + 1, "tool_outputs": updated_outputs}


def should_continue(state: AgentState) -> Literal["continue", "verifier"]:
    """Conditional edge: loop until all planned steps have been executed."""
    if state["current_step"] < len(state["plan"]):
        return "continue"
    return "verifier"


def verifier_node(state: AgentState) -> dict[str, Any]:
    """Verify all tool outputs and synthesize the final response."""
    summary = " | ".join(state["tool_outputs"])
    final = f"LangGraph 'Research Summarization' Agent completed all {len(state['plan'])} steps: {summary}"
    print(f"[VerifierNode] {final}")
    return {"final_answer": final}


# 4. Build & Compile the LangGraph StateGraph
def build_research_summarization_graph():
    if not LANGGRAPH_AVAILABLE:
        return None
    workflow = StateGraph(AgentState)
    workflow.add_node("planner", planner_node)
    workflow.add_node("agent", agent_executor_node)
    workflow.add_node("verifier", verifier_node)

    workflow.add_edge(START, "planner")
    workflow.add_edge("planner", "agent")
    workflow.add_conditional_edges(
        "agent",
        should_continue,
        {
            "continue": "agent",
            "verifier": "verifier",
        },
    )
    workflow.add_edge("verifier", END)
    return workflow.compile(checkpointer=MemorySaver())


def run_demo(task_prompt: str = "Automate research summarization workflow") -> str:
    print("=" * 65)
    print(f"Starting LangGraph Agent: Research Summarization")
    print("=" * 65)
    initial_state: AgentState = {
        "task": task_prompt,
        "plan": [],
        "current_step": 0,
        "tool_outputs": [],
        "final_answer": "",
    }
    app = build_research_summarization_graph()
    if app is not None:
        config = {"configurable": {"thread_id": "research_summarization-session-1"}}
        result = app.invoke(initial_state, config=config)
        return result["final_answer"]

    # Standalone execution when langgraph package is not installed in current env
    state = dict(initial_state)
    state.update(planner_node(state))  # type: ignore
    while should_continue(state) == "continue":  # type: ignore
        state.update(agent_executor_node(state))  # type: ignore
    state.update(verifier_node(state))  # type: ignore
    return str(state["final_answer"])


if __name__ == "__main__":
    run_demo()
