def intercept_and_save_llm_code(raw_reply: str, user_text: str = "") -> tuple[str, Path | None]:
    """If the LLM ever outputs a fenced code block or raw HTML document in chat,
    strip the code from the spoken reply, save it to Vani_Workspace, and open it!
    """
    fence_re = re.compile(r"```(?P<lang>[a-zA-Z0-9_-]*)\s*\n?(?P<code>[\s\S]+?)```")
    m = fence_re.search(raw_reply)
    code_content = ""
    lang = "python"

    if m:
        lang = (m.group("lang") or "").lower().strip()
        code_content = m.group("code").strip()
    elif "<!doctype html" in raw_reply.lower() or "<html" in raw_reply.lower():
        idx = raw_reply.lower().find("<!doctype html")
        if idx == -1:
            idx = raw_reply.lower().find("<html")
        code_content = raw_reply[idx:].strip()
        lang = "html"

    if not code_content:
        return raw_reply, None

    ws = get_workspace_dir()
    slug = re.sub(r"[^a-z0-9]+", "_", (user_text or "generated").lower()).strip("_")[:24] or "generated"
    is_html = lang in ("html", "htm", "xml") or code_content.lstrip().lower().startswith(("<!doctype", "<html"))
    ext = ".html" if is_html else ".py"
    out_path = ws / f"vani_{slug}{ext}"
    out_path.write_text(code_content + "\n", encoding="utf-8")
    open_file_in_editor(out_path, also_open_browser=is_html)

    spoken = f"I've created the {'HTML file' if is_html else 'Python file'} {out_path.name} in your Vani Workspace folder and opened it on your screen."
    return spoken, out_path


