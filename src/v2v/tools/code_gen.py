class CodeGenTool(BaseTool):
    """Generates clean runnable Python scripts or HTML pages on Desktop and opens them."""

    name = "code_gen"
    description = "Write a Python script or HTML webpage by voice to Desktop and open it immediately."
    parameters = {
        "language": "'python' or 'html'",
        "topic": "Program or webpage topic requested by the user",
    }

    def execute(self, **kwargs: Any) -> ToolResult:
        lang = str(kwargs.get("language", "python")).lower().strip()
        topic = str(kwargs.get("topic", "demo")).strip(" .,!?\"'")
        dry_run = bool(kwargs.get("dry_run", False))

        desktop = _get_desktop_dir()
        if lang == "html":
            slug = re.sub(r"[^a-z0-9]+", "_", topic.lower()).strip("_") or "page"
            out_path = desktop / f"Vani_Web_{slug[:30]}.html"
            out_path.write_text(_render_html_template(topic), encoding="utf-8")
            if not dry_run:
                webbrowser.open(out_path.as_uri())
            spoken = f"Created an HTML page for {topic} on your Desktop and opened it in the browser."
            return ToolResult(True, spoken, spoken_response=spoken, data={"path": str(out_path), "language": "html"})

        # Python generation
        t_low = topic.lower()
        slug = re.sub(r"[^a-z0-9]+", "_", t_low).strip("_") or "script"
        code = ""
        for keywords, tmpl_slug, tmpl_code in _PYTHON_TEMPLATES:
            if any(k in t_low for k in keywords):
                slug = tmpl_slug
                code = tmpl_code
                break

        if not code:
            code = f'''"""Auto-generated Python starter for: {topic}."""


def main() -> None:
    print("Running {topic} task...")


if __name__ == "__main__":
    main()
'''

        out_path = desktop / f"Vani_Code_{slug[:30]}.py"
        out_path.write_text(code, encoding="utf-8")

        if not dry_run and os.name == "nt":
            code_bin = shutil.which("code") or shutil.which("code.cmd")
            if code_bin:
                subprocess.Popen([code_bin, str(out_path)], shell=True)
            else:
                subprocess.Popen(["notepad.exe", str(out_path)])

        spoken = f"Wrote a Python script for {topic} to your Desktop and opened it."
        return ToolResult(True, spoken, spoken_response=spoken, data={"path": str(out_path), "language": "python"})
