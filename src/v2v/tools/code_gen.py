def get_workspace_dir() -> Path:
    """Return `Desktop/Vani_Workspace` (or project `Vani_Workspace` fallback), creating it if needed."""
    for candidate in (_get_desktop_dir() / "Vani_Workspace", _PROJECT_ROOT / "Vani_Workspace"):
        try:
            candidate.mkdir(parents=True, exist_ok=True)
            test_file = candidate / ".write_test"
            test_file.write_text("ok", encoding="utf-8")
            test_file.unlink(missing_ok=True)
            return candidate
        except Exception:
            continue
    fallback = _PROJECT_ROOT / "Vani_Workspace"
    fallback.mkdir(parents=True, exist_ok=True)
    return fallback


def open_file_in_editor(path: Path, also_open_browser: bool = False) -> None:
    """Open the generated file visibly in VS Code (preferred) or Notepad, plus browser for HTML."""
    if os.name != "nt":
        return
    try:
        if also_open_browser and path.suffix.lower() in (".html", ".htm"):
            webbrowser.open(path.as_uri())
        code_bin = shutil.which("code") or shutil.which("code.cmd")
        if code_bin:
            subprocess.Popen([code_bin, str(path)], shell=True)
        else:
            subprocess.Popen(["notepad.exe", str(path)])
    except Exception as e:
        logger.warning("Failed to open %s in editor: %s", path, e)


